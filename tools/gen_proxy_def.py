#!/usr/bin/env python3
"""Generate the OpenAL32 forwarding .def for the HYPRLODR proxy DLL.

Reads the export table of the shipped OpenAL32.dll and emits one PE forwarder
per named export pointing at the renamed original (OpenAL32_real.dll). Pure
forwarders mean zero reimplementation of audio behaviour: the Windows loader
resolves each export straight into the real library.

Usage: gen_proxy_def.py <original OpenAL32.dll> <output .def> [real-module-name]
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from hyprl_diagnose import PEInfo  # noqa: E402


def main(argv: list[str]) -> int:
    if len(argv) < 2:
        print(__doc__)
        return 2
    source = pathlib.Path(argv[0])
    output = pathlib.Path(argv[1])
    real = argv[2] if len(argv) > 2 else "OpenAL32_real"

    info = PEInfo(source)
    if info.error:
        print(f"cannot parse {source}: {info.error}")
        return 1
    if not info.exports:
        print(f"{source} exposes no named exports; refusing to build a proxy")
        return 1

    lines = [
        "; Generated by tools/gen_proxy_def.py - do not edit by hand.",
        "; Every named export forwards to the renamed original library.",
        "LIBRARY OpenAL32.dll",
        "EXPORTS",
    ]
    for name in info.exports:
        lines.append(f"  {name}={real}.{name}")
    output.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(info.exports)} forwarded exports to {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
